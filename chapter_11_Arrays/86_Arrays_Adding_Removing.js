//Adding and removing from array

let arr = [1, 2, 3];
console.log(arr);

//Add to End
arr.push(4);
console.log(arr);

//remove from end
arr.pop();
console.log(arr);

arr.push(5, 6);
console.log(arr);


//Add to begin
arr.unshift(10);
console.log(arr);

//Remove from begin
arr.shift();
console.log(arr);
